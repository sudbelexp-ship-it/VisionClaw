// VisionClaw - VisionIntent.swift
// Нужен ли этому вопросу снимок.
//
// Без этого приложение выглядело сломанным ровно там, где обещало больше всего: на пустом экране
// предлагается «Что ты видишь?», человек нажимает — и уходит один текст. Модель честно отвечает,
// что ничего не видит, и выглядит это как «зрение не работает», хотя не работал здравый смысл.
//
// Решается не «умностью», а списком: вопрос про то, что перед глазами, почти всегда содержит одно
// из нескольких слов. Список намеренно короткий и проверяемый — лучше иногда не снять, чем снимать
// на каждый вопрос и жечь деньги и батарею на «как дела».

import Foundation

enum VisionIntent {
    /// Корни слов, а не целые слова: русский склоняет всё, и «надпись/надписи/надписью» должны
    /// ловиться одним «надпис».
    private static let markers = [
        "виж", "вид", "смотр", "посмотр", "гляд",
        "это что", "что это", "что за", "чё это", "что тут", "что здесь", "что передо",
        "прочит", "прочти", "читай", "надпис", "текст на", "написано",
        "на фото", "на снимке", "на картинке", "на изображ",
        "сфотограф", "сними", "кадр",
        "вокруг", "передо мной", "перед мной",
        "какого цвета", "какой цвет", "сколько тут", "сколько здесь",
        "переведи надпис", "переведи текст",
    ]

    /// Вопрос про окружающее — значит, к нему нужен кадр.
    static func needsPhoto(_ text: String) -> Bool {
        let normalized = text
            .folding(options: [.diacriticInsensitive, .caseInsensitive], locale: nil)
            .replacingOccurrences(of: "ё", with: "е")
        return markers.contains { normalized.contains($0) }
    }
}
